// Definitions for the symbols rusty_v8's prebuilt library expects from the
// Rust side of the v8 crate (src/*.rs) and from the temporal_rs crate, which
// swimming does not use:
//
//   - rusty_v8's Rust callbacks: custom platforms, the inspector, value
//     serializer delegates and cppgc's RustObj wrapper. V8Engine uses none of
//     these features, so nothing calls them.
//   - temporal_rs_*: V8's Temporal built-ins. V8Engine starts V8 with
//     --no-harmony-temporal, so `Temporal` does not exist in JS, as with
//     QuickJS.
//
// Only the names matter to the linker (C linkage); each stub stops the
// process if it is ever reached.
#include <cstdio>
#include <cstdlib>

namespace {
    [[noreturn]] void unavailable(const char* name) {
        std::fprintf(stderr, "swimming: V8 called %s, which swimming's V8 build does not provide\n", name);
        std::abort();
    }
}

#define SWIMMING_V8_STUB(name) \
    extern "C" void name() { unavailable(#name); }

